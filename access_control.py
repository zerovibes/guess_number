from functools import wraps

from constants import ADMIN_USERNAME, UNKNOWN_COMMAND


def access_control(func):
    
    # Здесь wraps — это фабрика декоратора: wraps(func) возвращает 
    # функцию-«копировальщик», и @ применяет её к wrapper. По существу 
    # это одно действие — update_wrapper(wrapper, func), только 
    # в декораторной записи.
    
    # update_wrapper(wrapper, func) делает ровно одно: 
    # переносит «визитную карточку» с func на wrapper — 
    # __name__, __qualname__, __module__, __annotations__, __doc__, 
    # обновляет __dict__ — и ставит ссылку wrapper.__wrapped__ = func. 
    # Именно __wrapped__ — главная механика, дальше к ней всё сводится.
    
    # ────────────────────────────────────────────────────────────────────────────
    # @wraps(func) — «сервисная» обёртка из functools, которую стоит накладывать
    # практически на любой собственный декоратор. Она не меняет логику вызова,
    # но сохраняет «визитную карточку» оригинала: когда access_control заменяет
    # метод на wrapper, @wraps(func) переносит с func на обёртку метаданные
    # (__name__, __qualname__, __module__, __doc__, __annotations__, __dict__)
    # и, главное, устанавливает ссылку wrapper.__wrapped__ = func.
    # Результат: Game.get_statistics.__name__ остаётся 'get_statistics'
    # (а не 'wrapper'), а инспекция, идущая по __wrapped__ (inspect.signature(),
    # help(), pytest, FastAPI, traceback), видит настоящую сигнатуру (self) -> None,
    # а не (*args, **kwargs). Без @wraps декоратор не ломает вызов, но делает
    # функцию «невидимой» для интроспекции — именно поэтому @wraps(func)
    # считается стандартной практикой и почти обязательной частью любого
    # собственного декоратора.
    # ────────────────────────────────────────────────────────────────────────────
    # Когда @wraps(func) НЕ стоит использовать
    # ────────────────────────────────────────────────────────────────────────────
    # Правило по умолчанию - ставить @wraps(func). Исключения - всего несколько,
    # и во всех них wrapper'ы «свои» метаданные - это «правда», а не дефект:
    #
    # 1. Декоратор намеренно меняет сигнатуру или контракт вызова
    #    (добавляет/убирает аргументы, меняет их имена или типы). В таком случае
    #    именно сигнатура wrapper'а - то, что реально передаёт вызывающий код,
    #    и копирование метаданных оригинала (особенно __wrapped__) вводит в
    #    заблуждение: inspect.signature() должна показать wrapper, а не то,
    #    что было «до».
    #
    # 2. Результатом декоратора является не функция, а другой объект-дескриптор
    #    (property, кэш, прокси с собственным поведением): wraps просто бессмысленно
    #    копирует атрибуты, неприменимые к этому объекту, а __wrapped__ ведёт в тупик.
    #
    # 3. Намеренное сокрытие оригинала (инкапсуляция): прокси/фасад, который
    #    не должен раскрывать внутреннюю функцию. Тогда __wrapped__ - это «дыра»,
    #    его отсутствие - осознанное решение, а не «забыли».
    #
    # 4. Декоратор-«маркер», который ничего не оборачивает, а лишь размечает
    #    (кладёт атрибут/метку на функцию и возвращает её как есть): оборачивать
    #    нечего, и wraps даст ровно те же метаданные, что уже есть.
    #
    # Логика выбора короткая: если внешний код (человек, фреймворк, inspect)
    # должен видеть ОБЛИК ОБЁРТКИ - не ставьте @wraps; если внешний код должен
    # видеть ОБЛИК ОРИГИНАЛА - ставляйте @wraps(func) без раздумий.
    # ────────────────────────────────────────────────────────────────────────────
    
    @wraps(func)
    def wrapper(self, *args, **kwargs):
        # self.username — instance-атрибут (назначается в __init__)
        # self.total_games — class-атрибут (цепочка: объект → класс)

        if self.username == ADMIN_USERNAME:
            result = func(self, *args, **kwargs)
            return result
        else:
            print(UNKNOWN_COMMAND)
       
    return wrapper
